#!/usr/bin/env bash
#
# PostToolUse(`Agent`|`Task`) lifecycle hook — handoff validator.
# Fires in the PARENT session the moment a subagent returns. The harness contract
# is that an implementer closes with `impl_<feature>.md` and a reviewer with
# `review_<feature>.md` under the engine's progress dir — those files ARE the
# handoff the orchestrator (and the publisher) read. A subagent that returns
# having left an empty or structurally-broken handoff silently corrupts that
# chain. This hook catches the obvious failure modes deterministically.
#
# WHY NOT SubagentStop, the event this hook is still NAMED after (#774). The
# reader of this note is the ORCHESTRATOR, and SubagentStop cannot reach it: there the
# `additionalContext` goes to the subagent that just stopped — it keeps that
# child running — and the host's doc names the alternative outright, "to inject
# context into the parent session after a subagent returns, use a `PostToolUse`
# hook on the `Agent` tool instead". Registered on SubagentStop the only channel
# left was `systemMessage`, which the doc defines as a "warning message shown to
# the user", so a note written in the imperative to the model arrived at the
# human's UI and nowhere else.
#
# The move also settles the firing rate #560 measured: SubagentStop fired 117
# times for 19 subagents in one session, each firing re-reporting the identical
# handoff. A PostToolUse on the Agent tool fires exactly once per return.
#
# The id and the filename keep the old spelling on purpose: they are a managed
# marker stamped into every already-rendered repo and the name the audit log has
# recorded under for a year of sessions. Renaming them would buy tidiness and
# cost the continuity of the measurement.
#
# DESIGN — advisory, never blocking. Emits `hookSpecificOutput.additionalContext`
# for the orchestrator plus a `systemMessage` so the human sees it too; it NEVER
# returns `decision: block`.
#
# Since spec 0030 (#985, R10) it reads `tool_input.subagent_type` — the
# Agent/Task tool call's OWN parameter, mirrored into every PreToolUse/PostToolUse
# payload (https://code.claude.com/docs/en/hooks.md: "payload carries `tool_name`,
# `tool_input`, `session_id`, `cwd`"). This is NOT the `agent_id`/`agent_type` pair
# the same doc says is "present only when the hook fires inside a subagent call" —
# that pair answers "am I running INSIDE a subagent", a question this hook (firing
# on the PARENT's own PostToolUse(Agent|Task)) never needs to ask. `subagent_type`
# is simply the argument the orchestrator passed to dispatch, so it is present on
# this exact event regardless of nesting. So the hook now knows WHICH subagent
# just returned and demands the matching contract:
#   - `implementer` → `impl_*.json` (R2): missing, unparseable, a `status` other
#     than `DONE`/`BLOCKED`, or any required key absent.
#   - `scribe` → `impl_*.md` missing its terminal `Status:` marker.
#   - anything else — another role, another engine, or a payload where the field
#     is absent — falls back to checking BOTH shapes wherever a matching file
#     exists. That is the identity-blind behavior this hook always had, kept as
#     the safety net for what `subagent_type` doesn't cover.
# It also always flags, regardless of identity:
#   - empty / whitespace-only handoffs, OR
#   - `review_*.md` missing a verdict (APPROVED / CHANGES_REQUESTED).
# It never invents an expectation, so a legitimate report never trips it, and a
# missing file is not flagged (a subagent may not produce a handoff at all).
# Accepted limitation: during parallel work a still-in-flight report from
# ANOTHER running subagent could momentarily look incomplete — advisory-only, so
# a false positive is a harmless note, never a block.
#
# The managed block is regenerated by `navori render`; do NOT edit by hand.
set -euo pipefail

# The payload was drained and discarded here; it is kept now because the audit
# recorder reads `session_id`/`cwd` out of it. Draining is still the point: an
# undrained stdin can leave the host writing into a closed pipe.
payload=$(cat 2>/dev/null) || payload=""

navori_audit_name="subagent-stop-handoff"
navori_audit_phase="PostToolUse"

# Where the problem set last REPORTED in this session is remembered (#560).
#
# The 117-firings-for-19-subagents problem this was written for is gone: on
# PostToolUse(`Agent`) the host fires once per return (#774). The stamp STAYS,
# and the move is what makes it matter more rather than less. A broken handoff
# stays broken until somebody fixes it, so without this every later subagent
# return in the same session re-reports it — and the note now travels through
# `additionalContext`, i.e. it is spent out of the orchestrator's context window, not
# out of a UI line the host draws for free.
#
# Parsed with parameter expansion, never jq: this must work whether or not
# audit-mode is on, and jq may not exist. Keyed by session AND repo so two
# sessions never silence each other. In the OS temp dir, so nothing lands in the
# user's tree and a reboot is a clean slate.
# A raw, unexpanded asset must remain advisory rather than exiting 127.
# Rendered includes replace these no-ops with the shared Spec 0035 adapter.
payload_field() { :; }
nv_subagent_type() { :; }
# Shared hook boilerplate — inlined into each hook at render time (see the
# include directive in the source scripts + lib/render/hook-includes.ts). Single source
# of truth for the sibling gate scripts; DO NOT copy this body back into a hook
# by hand (that is the drift #225/#261 removed).
#
# PreToolUse(Bash) passes the tool input on stdin. Read one field out of it
# WITHOUT hard-depending on jq (NOT preinstalled on macOS): try jq, then node
# (Claude Code's own runtime), then a best-effort sed unwrap on the leaf key.
# Nothing extracted → empty output, and each caller decides what that means (the
# gate scripts scan defensively; guard-destructive waves the command through).
#
# $1 is a dotted path written HERE, never user input — the payload is the data.
# Generic on purpose: `.cwd` feeds the worktree resolver of #454 through the
# SAME hardened cascade instead of a second copy of it.
#
# The sed fallback reads a JSON string through its first unescaped quote. JSON
# object member order is not a host contract: `command` can precede `cwd`, so a
# greedy capture to the last quote would swallow the rest of the payload when
# neither jq nor node is available.
# `${payload-$(cat)}` (unset test, not `:-`) rather than an unconditional
# `payload=$(cat)`: a caller that already captured stdin itself (spec 0035 —
# `managed-drift-watch.sh` needs the audit recorder's session_id/cwd even on
# tool names this hook does not otherwise read) keeps that value, empty or
# not, instead of this partial re-reading an already-drained pipe and
# clobbering it with "".
payload=${payload-$(cat)}
payload_field() {
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$payload" | jq -r ".$1 // empty" 2>/dev/null && return 0
  fi
  if command -v node >/dev/null 2>&1; then
    printf '%s' "$payload" | node -e 'let s="";const p=process.argv[1].split(".");process.stdin.on("data",c=>s+=c).on("end",()=>{try{let v=JSON.parse(s);for(const k of p)v=v?.[k];process.stdout.write(String(v??""))}catch{}})' "$1" 2>/dev/null && return 0
  fi
  printf '%s' "$payload" | sed -nE "s/.*\"${1##*.}\"[[:space:]]*:[[:space:]]*\"(([^\"\\]|\\.)*)\".*/\\1/p"
}
extract_cmd() {
  payload_field tool_input.command
}
